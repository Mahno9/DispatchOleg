/**
 * Платформенный инструктаж: что показать поверх рабочей области, пока игра
 * смонтирована, но заморожена (`handle.setPaused`, minigame_contract.md).
 * Ключ — `minigameId`, порядок в массиве = номер шага на экране.
 *
 * Шаг целится в ЭЛЕМЕНТ игры (`target` — CSS-селектор), а проценты отсчитываются
 * внутри его прямоугольника. Раньше это были проценты рабочей области — и они
 * разъезжались: игры вписывают поле с полями по краям (rescue-catch и three-mazes
 * вообще целиком в одном `<canvas>`), поэтому «50% высоты экрана» на широком
 * мониторе и на телефоне указывает в разные места. Селектор от пропорций не зависит.
 *
 * `target` необязателен: без него (и если селектор ничего не нашёл — игра
 * переверстала разметку) проценты считаются от всей рабочей области, как раньше.
 *
 * Направление и точку внутри цели считать руками не надо: по умолчанию их выводит
 * `resolveStep` из того, где цель оказалась на экране — подпись всегда уезжает
 * внутрь, а стрелка садится на ближнюю к краю кромку цели. `dir`/`x`/`y` в шаге —
 * это переопределения, нужные там, где несколько шагов целятся в один элемент
 * (игры на `<canvas>`) и их подписи иначе наедут друг на друга.
 *
 * «Уже видел» запоминается: `minigameId` попадает в `briefedMinigames`
 * состояния игрока (state/localState.ts), и на повторной попытке стрелки сами
 * не всплывают — их вызывает кнопка «?» в углу игры. Поле едет в `/api/sync`
 * внутри состояния; сервер объединяет списки так же, как `seenDialogues`
 * (mergeBriefedMinigames), и клиент склеивает их у себя (localState.replace).
 */
export interface TutorialStep {
  /** CSS-селектор цели внутри игры. Без него проценты — от всей рабочей области. */
  target?: string;
  /**
   * Пропорция картинки внутри цели (ширина/высота). Нужна для игр на `<canvas>`:
   * холст растянут на всю область, а мир рисуется по центру с `min(cw/W, ch/H)`,
   * и без этой поправки стрелка целится в поле, а не в то, что на нём нарисовано.
   *
   * ponytail: пропорция мира продублирована здесь из кода игры. Апгрейд — игра
   * сама сообщает свой видимый прямоугольник через контракт; до тех пор при смене
   * мира в игре правится и это число.
   */
  aspect?: number;
  /** Точка внутри цели по горизонтали, % её ширины. По умолчанию — от `dir`. */
  x?: number;
  /** Точка внутри цели по вертикали, % её высоты. По умолчанию — от `dir`. */
  y?: number;
  /** Куда смотрит остриё; подпись встаёт с противоположной стороны. По умолчанию — от места цели. */
  dir?: Dir;
  text: string;
}

export type Dir = 'up' | 'down' | 'left' | 'right';

/** Прямоугольник в координатах вьюпорта — ровно то, что даёт `getBoundingClientRect`. */
export interface Box {
  left: number;
  top: number;
  width: number;
  height: number;
}

/**
 * Куда развернуть шаг, если в нём не сказано: подпись должна уезжать к центру
 * экрана, иначе её обрежет краем. Цель у левой трети — стрелка смотрит влево и
 * подпись идёт вправо, у правой — зеркально, посередине — вверх/вниз.
 */
export function autoDir(host: Box, target: Box | null): Dir {
  if (!target || !host.width || !host.height) return 'up';
  const cx = (target.left + target.width / 2 - host.left) / host.width;
  const cy = (target.top + target.height / 2 - host.top) / host.height;
  if (cx < 1 / 3) return 'left';
  if (cx > 2 / 3) return 'right';
  return cy < 0.5 ? 'up' : 'down';
}

/**
 * Точка внутри цели по умолчанию — у той её кромки, в которую смотрит стрелка.
 * Из центра подпись пришлось бы задвигать зажимом прямо на собственную стрелку.
 */
export function autoPoint(dir: Dir): { x: number; y: number } {
  if (dir === 'left') return { x: 90, y: 50 };
  if (dir === 'right') return { x: 10, y: 50 };
  if (dir === 'up') return { x: 50, y: 90 };
  return { x: 50, y: 10 };
}

/**
 * Позиция шага в процентах рабочей области плюс итоговое направление.
 * `target === null` — селектора нет или он ничего не нашёл: тогда работают
 * проценты самого шага (или центр), как до привязки к DOM.
 */
export function resolveStep(
  host: Box,
  target: Box | null,
  step: TutorialStep,
): { x: number; y: number; dir: Dir } {
  const box = target && step.aspect ? containBox(target, step.aspect) : target;
  const dir = step.dir ?? autoDir(host, box);
  const point = autoPoint(dir);
  const x = step.x ?? point.x;
  const y = step.y ?? point.y;
  if (!box || !host.width || !host.height || !box.width || !box.height) {
    return { x: step.x ?? 50, y: step.y ?? 50, dir };
  }
  return {
    x: ((box.left - host.left + (box.width * x) / 100) / host.width) * 100,
    y: ((box.top - host.top + (box.height * y) / 100) / host.height) * 100,
    dir,
  };
}

/** Прямоугольник данной пропорции, вписанный по центру `outer` — тот же `object-fit: contain`. */
function containBox(outer: Box, aspect: number): Box {
  const width = Math.min(outer.width, outer.height * aspect);
  const height = width / aspect;
  return {
    left: outer.left + (outer.width - width) / 2,
    top: outer.top + (outer.height - height) / 2,
    width,
    height,
  };
}

